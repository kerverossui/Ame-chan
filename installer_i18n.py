def get_language() -> str:
    """The saved language, or the AME_LANG environment variable, or English."""
    env = os.environ.get("AME_LANG", "").strip().lower()[:2]
    if env in TEXTS:
        return env
    try:
        with open(_LANG_FILE, encoding="utf-8") as f:
            code = f.read().strip().lower()[:2]
        if code in TEXTS:
            return code
    except OSError:
        pass
    return DEFAULT


def save_language(code: str) -> None:
    if code in TEXTS:
        try:
            with open(_LANG_FILE, "w", encoding="utf-8") as f:
                f.write(code)
        except OSError:
            pass


def t(key: str, lang: str | None = None, **kw) -> str:
    lang = lang or get_language()
    text = TEXTS.get(lang, {}).get(key) or TEXTS[DEFAULT].get(key, key)
    return text.format(**kw) if kw else text
